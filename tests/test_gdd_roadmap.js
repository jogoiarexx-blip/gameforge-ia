const assert=require('node:assert/strict');
const plan=require('../js/gdd-roadmap.js');
const md='# Grande Jogo\n\n## Menus e HUD\n- Pause com opções\n\n## Fase 1 — Porto\n- Inimigos ao chegar\n\n## Combate\n- Tiro e inimigos\n\n## Áudio\n- Música de combate\n';
let tasks=plan.build(md);
assert.equal(tasks.length,4);assert.equal(plan.summary(tasks).pending,4);
assert.equal(tasks[0].kind,'Interface e menus');assert.equal(tasks[1].kind,'Fases e progressão');
assert.match(plan.context(tasks[2],md),/Tiro e inimigos/);
const id=tasks[1].id;tasks=plan.changeStatus(tasks,id,'aguardando revisão','QA testado');
assert.equal(plan.build(md,tasks).find(t=>t.id===id).status,'aguardando revisão');
assert.equal(plan.summary(tasks).review,1);
assert.match(plan.report(tasks,md),/QA testado/);
const mdModified=md+'\n## Chefe Final\n- Boss com três fases\n';
const next=plan.build(mdModified,tasks);
assert.equal(next.length,5);assert.equal(next.find(t=>t.id===id).status,'aguardando revisão');
const withFence=plan.build('# Jogo\n## Sistema\n```md\n## Falso cabeçalho\n```\n## Verdadeiro\n');
assert.equal(withFence.length,2);
const huge='# Jogo\n'+Array.from({length:280},(_,i)=>`\n## Fase ${i+1}\n${'Uma mecânica de progressão. '.repeat(55)}\n`).join('');
assert.ok(Buffer.byteLength(huge)>300000);const many=plan.build(huge);
assert.equal(many.length,280);assert.match(plan.context(many[279],huge),/Fase 280/);
assert.throws(()=>plan.changeStatus(tasks,id,'pronto'),/inválido/);
console.log('OK roadmap GDD 300+ KB, capítulos finais, preservar status, busca por id e exportação');
